#!/usr/bin/env node
/* =========================================================================
   v09/tools/generate-vite-bridge.cjs

   Stage 11C1 — Vite Migration Bridge Generator
   Artifact Class: V09_TEST (migration infrastructure)

   Purpose: generate a package-managed React/Vite entry point that executes
   the ACCEPTED Stage 11B application source (34 modules, in accepted order,
   with all 19 historical ReactDOM.createRoot mount calls preserved) without
   converting the modules to ES modules and without any scientific or UI
   change.

   Reads the frozen Stage 11B source-order manifest
   (v09/tools/v09-source-order.json) and FAILS CLOSED if any application
   module's on-disk SHA-256 differs from its expected_current_v09_sha256 —
   the same fail-closed governance principle established in Stage 11B.

   Output: v09/app-bridge/bridge-entry.generated.jsx
   This file is GENERATED. Do not hand-edit it. Regenerate with:
     node v09/tools/generate-vite-bridge.cjs
   (or: npm run bridge:generate, from v09/)
   ========================================================================= */
'use strict';

const fs     = require('fs');
const path   = require('path');
const crypto = require('crypto');

const V09 = path.join(__dirname, '..');
const MANIFEST_PATH = path.join(__dirname, 'v09-source-order.json');
const OUT_DIR = path.join(V09, 'app-bridge');
const OUT_FILE = path.join(OUT_DIR, 'bridge-entry.generated.jsx');
const CSS_OUT = path.join(OUT_DIR, 'bridge-styles.generated.css');

function sha256(content) {
  return crypto.createHash('sha256').update(content).digest('hex');
}

function readAndVerify(relPath, expectedCurrentSha, label) {
  const full = path.join(V09, relPath);
  if (!fs.existsSync(full)) {
    console.error(`BRIDGE GENERATION FAIL: Missing source file: ${relPath}`);
    process.exit(1);
  }
  const content = fs.readFileSync(full, 'utf8');
  const actualSha = sha256(content);
  if (actualSha !== expectedCurrentSha) {
    console.error(`\nBRIDGE GENERATION FAIL: Unexpected SHA drift`);
    console.error(`  file:                       ${relPath} (${label})`);
    console.error(`  expected current v0.9 SHA:  ${expectedCurrentSha}`);
    console.error(`  actual SHA:                 ${actualSha}`);
    console.error(`\nThe Vite bridge will NOT be generated from unverified source.`);
    console.error(`This preserves the Stage 11B two-SHA fail-closed governance model.`);
    process.exit(1);
  }
  return content;
}

console.log('=== Stage 11C1 Vite Bridge Generation (fail-closed SHA governance) ===');

if (!fs.existsSync(MANIFEST_PATH)) {
  console.error('BRIDGE GENERATION FAIL: v09-source-order.json manifest not found.');
  process.exit(1);
}
const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));

if (!Array.isArray(manifest.application_modules) || manifest.application_modules.length !== 34) {
  console.error(`BRIDGE GENERATION FAIL: manifest does not list exactly 34 application modules (found ${manifest.application_modules?.length}).`);
  process.exit(1);
}

// 1. Verify and concatenate all 34 application modules in accepted order
console.log(`\nVerifying and concatenating ${manifest.application_modules.length} application modules:`);
let appSource = '';
for (const mod of manifest.application_modules) {
  const content = readAndVerify(mod.path, mod.expected_current_v09_sha256, `module ${mod.order}`);
  appSource += content;
  console.log(`  [${String(mod.order).padStart(2, '0')}/34] ${mod.path} (${content.split('\n').length}L) SHA-VERIFIED`);
}

const mountCount = (appSource.match(/ReactDOM\.createRoot\(/g) || []).length;
console.log(`\nReactDOM.createRoot mount calls in concatenated source: ${mountCount}`);
if (mountCount !== 19) {
  console.error(`BRIDGE GENERATION FAIL: Expected exactly 19 historical mount calls, found ${mountCount}. Stage 11C1 must preserve this count unchanged.`);
  process.exit(1);
}

// 2. Verify CSS
console.log('\nVerifying CSS...');
const css = readAndVerify(manifest.css.path, manifest.css.expected_current_v09_sha256, 'CSS');
console.log(`  CSS verified: ${css.split('\n').length} lines`);

if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(CSS_OUT, css, 'utf8');
console.log(`  CSS copied to ${path.relative(V09, CSS_OUT)} (verbatim, for build-time import)`);

// 3. Build the bridge entry file
// NOTE: no timestamps are embedded, to keep the generated output deterministic
// across repeated generation runs from the same accepted source.
const header = `/* =========================================================================
   GENERATED FILE — DO NOT HAND-EDIT

   Generated by: v09/tools/generate-vite-bridge.cjs
   Source manifest used: v09/tools/v09-source-order.json
   Regenerate with: node v09/tools/generate-vite-bridge.cjs
     (or: npm run bridge:generate, from v09/)

   This file wraps the ACCEPTED Stage 11B application source (34 modules,
   preserved in accepted dependency order, with all 19 historical
   ReactDOM.createRoot mount calls unchanged) so it can execute under a
   package-managed React/Vite build. No module-level, scientific, or UI
   changes are made here — Stage 11C1 is a build/runtime bridge only.
   ========================================================================= */

import React from "react";
import { createRoot } from "react-dom/client";
import "./bridge-styles.generated.css";

// Expose package React and react-dom/client under the identifiers expected
// by the accepted Stage 11B legacy source (which references bare "React"
// and calls ReactDOM's createRoot API). This is the minimum bridge wrapper
// required — no other API surface is introduced.
// eslint-disable-next-line no-unused-vars
const ReactDOM = { createRoot };

`;

const footer = `
/* ========================================================================
   END OF CONCATENATED STAGE 11B APPLICATION SOURCE (34 MODULES)
   ======================================================================== */
`;

const bridgeContent = header + appSource + footer;
fs.writeFileSync(OUT_FILE, bridgeContent, 'utf8');

console.log(`\n=== Bridge Generation Complete ===`);
console.log(`Output: ${path.relative(V09, OUT_FILE)}`);
console.log(`Size: ${Buffer.byteLength(bridgeContent, 'utf8')} bytes`);
console.log(`Modules concatenated: ${manifest.application_modules.length}`);
console.log(`Mount calls preserved: ${mountCount}`);
console.log(`Bridge content SHA-256: ${sha256(bridgeContent)}`);
